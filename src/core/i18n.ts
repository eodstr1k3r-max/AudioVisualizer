const dicts: Record<Lang, Record<TKey, string>> = { de, en };

export type { TKey };

/** Übersetzt den Key in die aktuell eingestellte Sprache (für Nicht-React-Code). */
export function t(key: TKey): string {
  const lang = useStore.getState().settings.lang;
  return dicts[lang]?.[key] ?? de[key] ?? key;
}

/** React-Hook: liefert die Übersetzungsfunktion (re-rendert bei Sprachwechsel). */
export function useT(): (key: TKey) => string {
  const lang = useStore((s) => s.settings.lang);
  return (key: TKey) => dicts[lang]?.[key] ?? de[key] ?? key;
}

/**
 * Übersetzt einen optionalen i18n-Key, falls vorhanden – sonst wird `fallback` genutzt.
 * Für Bereiche wie Modus-/Preset-Namen, die (noch) nicht vollständig im Wörterbuch stehen:
 * einzelne Einträge (z. B. 'modes.solarsystem') können so übersetzt werden, ohne dass
 * alle anderen, bislang unübersetzten Namen ein Dictionary-Update brauchen.
 */
export function translateOrFallback(tr: (key: TKey) => string, key: string, fallback: string): string {
  if (!(key in de)) return fallback;
  const translated = tr(key as TKey);
  return translated === key ? fallback : translated;
}
